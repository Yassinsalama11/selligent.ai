function getEmailTemplate(templateName) {
  const key = String(templateName || '').trim();
  const template = templates[key];
  if (!template) {
    const err = new Error(`Unknown email template: ${templateName || ''}`);
    err.code = 'EMAIL_TEMPLATE_NOT_FOUND';
    err.status = 400;
    throw err;
  }
  return template;
}

function listEmailTemplates() {
  return Object.keys(templates);
}

