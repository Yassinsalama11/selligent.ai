const { interpolateValue } = require('./templateRenderer');

function getDefaultFooterLinks(vars = {}) {
  return [
    { label: 'Website', url: vars.website_url },
    { label: 'Contact', url: `mailto:${vars.support_email}` },
    { label: 'Privacy Policy', url: vars.privacy_url },
    { label: 'Terms', url: vars.terms_url },
  ];
}

function createTemplate(definition) {
  return (variables = {}) => ({
    ...interpolateValue(definition, variables),
    footerLinks: getDefaultFooterLinks(variables),
  });
}

